import fs from 'node:fs';
import {chromium,expect} from '@playwright/test';
const origin=process.env.TEST_ORIGIN||'http://127.0.0.1:3005/website';
const articles=JSON.parse(fs.readFileSync('src/generated/english-editorial.json'));
const browser=await chromium.launch(),page=await browser.newPage({viewport:{width:390,height:844}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto(origin+'/en/articles/');
await page.locator('.archive-grid h2 a').first().click();
await expect(page.locator('main h1')).toHaveText(articles[0].title);
await page.goBack();
await expect(page.locator('.archive-grid article')).toHaveCount(12);
const target=articles.find(a=>a.href.includes('/19372-'));
await page.getByRole('searchbox').fill(target.title);
await page.locator('.archive-grid h2 a').first().click();
await expect(page.locator('main h1')).toHaveText(target.title);
await expect(page.locator('html')).toHaveAttribute('lang','en');
await page.waitForTimeout(500);
expect(errors).toEqual([]);
await browser.close();console.log('English archive → article, back, search → large article: passed');
